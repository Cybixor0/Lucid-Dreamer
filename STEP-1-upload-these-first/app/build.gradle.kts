/**
 * Release signing credentials, from `keystore.properties` locally or from
 * environment variables in CI.
 *
 * Both are gitignored / secret by construction: no key material ever enters the
 * repository. If neither is present the release build is simply left unsigned,
 * which is a normal and useful thing to produce - see docs/INSTALL.md.
 */
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(key: String, env: String): String? =
    keystoreProperties.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = signingValue("storeFile", "SIGNING_STORE_FILE")
val hasReleaseSigning = releaseStoreFile != null && file(releaseStoreFile).exists()

